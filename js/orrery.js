// Function to change / update project preview info
function showSelectedProject(project, plot) {
    previewTitle.textContent = project.title;
    previewDate.textContent = project.date;
    previewType.textContent = SECTORS[project.type].name;
    previewLink.href = project.url;
    previewTimeTaken.textContent = project.time;
    previewImage.src = project.thumbnail;
    previewImage.alt = project.title;

    if (!plot) return;
    if (selectedPlot) selectedPlot.classList.remove("selected"); // remove any previously selected plots
    selectedPlot = plot;
    plot.classList.add("selected"); // add selected class to current selected plot
}

