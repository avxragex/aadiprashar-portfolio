const MS_PER_YEAR = 365.25 * 24 * 60 * 60 * 1000;
const MAX_AGE = 3; // Oldest project year at outer ring
const R_MIN = 0.1; // To make sure no plot is at r = 0 (center)
const PAD = 0.02; // Keeping padding at sector edges

const list = document.querySelector(".orrery-plots");
const now = new Date();
let i = 0;

// Filter by sectors
for (const type in SECTORS) {
    // get each item in individual sector
    const items = PROJECTS.filter(project => project.type === type);

    const sector = SECTORS[type];
    const start = sector.start;
    const end = sector.end;
    const span = end - start - 2 * PAD; // usable sector width

    // Sort by the date
    items.sort((a, b) => new Date(a.date) - new Date(b.date));
    items.forEach((project, index) => {
        const turn = start + PAD + (index + 0.5) * (span / items.length);

        const age = (now - new Date(project.date)) / MS_PER_YEAR; // Get how old project is in years
        const t = Math.min(age / MAX_AGE, 1); // Convert overall age in terms of max from 0-1
        const r = R_MIN + t * (1 - R_MIN); // Get radius

        const li = document.createElement("li");
        li.className = "orrery-plot";
        li.style.setProperty("--turn", turn.toFixed(4));
        li.style.setProperty("--distance", `${(r * 50).toFixed(2)}%`);  // 50% = outer ring
        li.style.setProperty("--i", i++);

        const a = document.createElement("a");
        a.href = project.url;
        li.append(a);

        list.append(li);

        // Icon
        const icon = document.createElement("i");
        icon.className =  "bi " + project.icon;
        icon.setAttribute("aria-hidden", "true");
        a.append(icon);

        // Update preview plot when animation starts
        icon.addEventListener("animationstart", () => {
            showSelectedProject(project, li)
        });

        // Update prview plot when animation iterates
        icon.addEventListener("animationiteration", () => {
            showSelectedProject(project, li)
        });
    });
}
